const DICTS: Partial<Record<AppLocale, ChromeDict>> = {
  es: ES,
  en: EN,
};

export const LOCALE_LABELS: Record<AppLocale, string> = {
  es: 'Español',
  en: 'English',
  fr: 'Français',
  it: 'Italiano',
  de: 'Deutsch',
};

export function chromeT(key: string, locale: string): string {
  const base = (locale || 'es').split(/[-_]/)[0] as AppLocale;
  const dict = DICTS[base] || (base === 'es' ? ES : EN);
  return dict[key] || EN[key] || ES[key] || key;
}
